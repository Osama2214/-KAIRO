/**
 * A time-boxed price cut, on top of whatever `price` already is.
 *
 * The discount is stored rather than written into `price`, and the effective
 * price is worked out whenever it is read. That way an expired promotion stops
 * applying on its own — there is no scheduled job to run, and no window where
 * a lapsed offer is still being charged.
 */
export interface VolumePromo {
  /** Percent off the current selling price, 1-90. */
  percent: number;
  /** ISO timestamp. The offer stops the moment this passes. */
  endsAt: string;
  /** Optional ISO timestamp; before it, the offer has not started yet. */
  startsAt?: string;
  /** Short shop-facing label, e.g. "عرض الجمعة". */
  label?: string;
  labelArabic?: string;
}

/**
 * What kind of thing a catalogue record sells. Books predate the field, so a
 * record without one is a book; figures and posters always carry it.
 */
export type ProductType = "book" | "figure" | "poster";

/**
 * One purchasable option of a figure or poster — a poster size, a figure
 * edition. Each variant is its own row in `kairo_catalog_items` (see
 * `lib/variants.ts`), so it has its own price and its own stock, and checkout
 * reserves it exactly like a book.
 */
export interface ProductVariant {
  /** Stable key within the product: lowercase letters, digits, dashes. */
  sku: string;
  label: string;
  labelAr?: string;
  price: number;
  originalPrice?: number;
  stock: number;
  /**
   * One of the product's own photos (the main photo or a gallery photo) shown
   * when this variant is picked, and used for its cart and order line.
   */
  image?: string;
}

/** A free-form spec row, for anything the fixed fields do not cover. */
export interface ProductSpec {
  label: string;
  labelAr?: string;
  value: string;
  valueAr?: string;
}

export interface MerchDetails {
  /** Franchise the item belongs to, as free text ("Naruto"). */
  franchise?: string;
  franchiseAr?: string;
  // Figures
  manufacturer?: string;
  character?: string;
  characterAr?: string;
  heightCm?: number;
  material?: string;
  materialAr?: string;
  scale?: string;
  // Posters
  paperType?: string;
  paperTypeAr?: string;
  finish?: string;
  finishAr?: string;
  /** Anything else, shown after the fixed fields. */
  specs?: ProductSpec[];
}

export interface MangaVolume {
  id: string;
  /** Absent on books; see ProductType. */
  productType?: ProductType;
  /** Figures and posters: the options a shopper picks between. */
  variants?: ProductVariant[];
  /** Figures and posters: specs shown on the product page. */
  merch?: MerchDetails;
  /** Extra product photos, after `coverImage`. */
  gallery?: string[];
  /**
   * Set only on the per-variant catalogue rows derived by `lib/variants.ts`:
   * the product the row belongs to, and which variant it is.
   */
  parentId?: string;
  variantSku?: string;
  variantLabel?: string;
  variantLabelAr?: string;
  volumeNumber: number;
  title: string;
  seriesSlug: string;
  seriesTitle: string;
  japaneseTitle: string;
  author: string;
  artist: string;
  price: number;
  originalPrice?: number;
  rating: number;
  reviewCount: number;
  coverImage: string;
  synopsis: string;
  /**
   * The Arabic synopsis. Everything else on a product page switches language
   * with the locale; the description was the one thing left in English, so a
   * shopper reading the site in Arabic hit a wall of English at the part that
   * actually describes the book. Optional — an untranslated product falls back
   * to the English text rather than showing nothing.
   */
  synopsisAr?: string;
  format: "Manga" | "Light Novel" | "Box Set" | "Deluxe Edition" | "Figure" | "Poster";
  pages: number;
  publishDate: string;
  isbn: string;
  genre: string[];
  stock: number;
  isTrending?: boolean;
  isNewRelease?: boolean;
  isFeatured?: boolean;
  /**
   * Extra spellings the search should answer to — an Arabic
   * transliteration, a nickname, a common misspelling. Never displayed.
   */
  aliases?: string[];
  /**
   * For a Box Set: the volume ids it is assembled from.
   *
   * A bundle stores no stock and no list price of its own — both are derived
   * from these members whenever they are read, so the two can never disagree.
   */
  bundleOf?: string[];
  /** Limited-time offer layered on top of `price`; see VolumePromo. */
  promo?: VolumePromo;
  previewPages: string[];
}

